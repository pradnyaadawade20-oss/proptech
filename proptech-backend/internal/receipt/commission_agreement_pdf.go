package receipt

import (
	"fmt"
	"strings"
)

// CommissionAgreementData is the content of the broker <-> tenant commission agreement PDF.
type CommissionAgreementData struct {
	AgreementNumber string
	PropertyTitle   string
	AgentName       string
	TenantName      string
	Amount          float64
	Note            string

	AgentSignType  string // "draw" | "type"
	AgentSignData  string
	AgentSignedAt  string
	TenantSignType string
	TenantSignData string
	TenantSignedAt string
}

// BuildCommissionAgreement returns the commission agreement PDF (same look as the rental agreement).
func BuildCommissionAgreement(a CommissionAgreementData) []byte {
	d := &agDoc{}
	d.newPage()

	d.cur.WriteString("0.082 0.333 0.541 rg 0 742 595 100 re f\n1 1 1 rg\n")
	d.text("F2", 22, 50, 792, "COMMISSION AGREEMENT")
	d.text("F1", 11, 50, 768, "Agreement No: "+clean(a.AgreementNumber, 50))
	d.text("F1", 11, 50, 752, "Status: Signed by both parties")
	d.cur.WriteString("0 0 0 rg\n")
	d.y = 715

	intro := fmt.Sprintf("This agreement is made between %s (the Agent) and %s (the Tenant) about the Agent's commission for the property described below. It is separate from the rental agreement between the Tenant and the property owner. Both parties have agreed to the terms in this document and have signed it digitally on PropTech.",
		clean(a.AgentName, 60), clean(a.TenantName, 60))
	for _, l := range agWrap(intro, 92) {
		d.text("F1", 10, 50, d.y, l)
		d.y -= 14
	}

	d.section("Parties")
	d.kv("Agent (Broker)", a.AgentName)
	d.kv("Tenant", a.TenantName)

	d.section("Property")
	d.kv("Property", a.PropertyTitle)

	d.section("Commission")
	d.kv("Commission amount", money(a.Amount))
	if strings.TrimSpace(a.Note) != "" {
		d.kv("Note", a.Note)
	}

	d.section("Terms")
	terms := []string{
		"1. The Tenant agrees to pay the commission above to the Agent for helping the Tenant find this property.",
		"2. The commission becomes payable after the rental agreement for this property has been signed by both the owner and the Tenant.",
		"3. The commission is paid through the PropTech app, and a payment receipt is available to both parties.",
		"4. This agreement is only between the Agent and the Tenant. The property owner is not a party to it, and it does not change the rental agreement.",
	}
	for _, t := range terms {
		for _, l := range agWrap(t, 92) {
			d.ensure(14)
			d.text("F1", 10, 50, d.y, l)
			d.y -= 14
		}
		d.y -= 4
	}

	d.section("Signatures")
	d.ensure(130)
	d.signature(50, "Agent", a.AgentName, a.AgentSignType, a.AgentSignData, a.AgentSignedAt)
	d.signature(320, "Tenant", a.TenantName, a.TenantSignType, a.TenantSignData, a.TenantSignedAt)
	d.y -= 125

	for i, p := range d.pages {
		fmt.Fprintf(p, "0 0 0 rg BT /F1 8 Tf 50 40 Td (%s) Tj ET\n",
			esc(fmt.Sprintf("Generated by PropTech  |  Commission agreement %s  |  Page %d of %d", clean(a.AgreementNumber, 40), i+1, len(d.pages))))
	}
	return d.assemble()
}