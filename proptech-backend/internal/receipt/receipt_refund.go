package receipt

import (
	"bytes"
	"fmt"
)

// RefundDeduction is one line taken off the deposit.
type RefundDeduction struct {
	Category string
	Reason   string
	Amount   float64
}

// RefundData is everything on a deposit refund receipt.
type RefundData struct {
	ReceiptNo       string
	PropertyTitle   string
	TenantName      string
	OwnerName       string
	LeasePeriod     string
	DepositPaidOn   string // date + time
	RefundedOn      string // date + time
	Method          string
	Reference       string
	DepositAmount   float64
	Deductions      []RefundDeduction
	TotalDeductions float64
	TenantOwes      float64
	RefundAmount    float64
	GeneratedOn     string // date + time
}

const maxRefundLines = 8

// BuildRefund returns a one-page "deposit refund receipt" PDF.
func BuildRefund(d RefundData) []byte {
	var c bytes.Buffer

	text := func(font string, size int, x, y int, s string) {
		fmt.Fprintf(&c, "BT /%s %d Tf %d %d Td (%s) Tj ET\n", font, size, x, y, esc(s))
	}
	line := func(x1, y1, x2, y2 int) {
		fmt.Fprintf(&c, "0.85 0.88 0.92 RG 0.8 w %d %d m %d %d l S\n", x1, y1, x2, y2)
	}

	// Header band
	c.WriteString("0.082 0.333 0.541 rg 0 742 595 100 re f\n")
	c.WriteString("1 1 1 rg\n")
	text("F2", 24, 50, 790, "DEPOSIT REFUND RECEIPT")
	text("F1", 11, 50, 766, "Receipt No: "+clean(d.ReceiptNo, 40))
	text("F1", 11, 360, 766, "Refunded on: "+clean(d.RefundedOn, 30))
	c.WriteString("0 0 0 rg\n")

	y := 705
	row := func(label, value string) {
		if value == "" {
			return
		}
		text("F2", 11, 50, y, label)
		text("F1", 11, 210, y, clean(value, 62))
		line(50, y-9, 545, y-9)
		y -= 28
	}
	row("Property", d.PropertyTitle)
	row("Tenant", d.TenantName)
	row("Landlord", d.OwnerName)
	row("Lease period", d.LeasePeriod)
	row("Deposit paid on", d.DepositPaidOn)
	row("Refunded on", d.RefundedOn)
	row("Refund mode", d.Method)
	row("Reference", d.Reference)

	// Settlement box
	shown := d.Deductions
	extra := 0
	extraAmt := 0.0
	if len(shown) > maxRefundLines {
		for _, x := range shown[maxRefundLines:] {
			extraAmt += x.Amount
		}
		extra = len(shown) - maxRefundLines
		shown = shown[:maxRefundLines]
	}
	lines := 1 // deposit
	lines += len(shown)
	if extra > 0 {
		lines++
	}
	if len(d.Deductions) == 0 {
		lines++ // "No deductions"
	}
	lines++ // total deductions
	if d.TenantOwes > 0 {
		lines++
	}
	boxH := lines*22 + 70
	top := y - 4
	fmt.Fprintf(&c, "0.94 0.96 0.98 rg 50 %d 495 %d re f\n0 0 0 rg\n", top-boxH, boxH)

	by := top - 24
	text("F2", 12, 65, by, "SETTLEMENT")
	by -= 24
	text("F1", 11, 65, by, "Security deposit held")
	text("F1", 11, 420, by, money(d.DepositAmount))
	by -= 22
	if len(d.Deductions) == 0 {
		text("F1", 11, 65, by, "No deductions")
		by -= 22
	}
	for _, x := range shown {
		label := x.Category
		if x.Reason != "" {
			label += ": " + x.Reason
		}
		text("F1", 11, 65, by, "- "+clean(label, 56))
		text("F1", 11, 420, by, "- "+money(x.Amount))
		by -= 22
	}
	if extra > 0 {
		text("F1", 11, 65, by, fmt.Sprintf("- %d more deduction(s)", extra))
		text("F1", 11, 420, by, "- "+money(extraAmt))
		by -= 22
	}
	text("F2", 11, 65, by, "Total deductions")
	text("F2", 11, 420, by, "- "+money(d.TotalDeductions))
	by -= 22
	if d.TenantOwes > 0 {
		text("F1", 11, 65, by, "Tenant still owes")
		text("F1", 11, 420, by, money(d.TenantOwes))
		by -= 22
	}
	line(65, by+10, 530, by+10)
	by -= 18
	text("F2", 14, 65, by, "REFUNDED TO TENANT")
	text("F2", 14, 420, by, money(d.RefundAmount))

	text("F1", 9, 50, 84, "This is a computer-generated receipt and does not need a signature.")
	if d.GeneratedOn != "" {
		text("F1", 9, 50, 70, "Generated on "+clean(d.GeneratedOn, 40)+" by PropTech.")
	} else {
		text("F1", 9, 50, 70, "Generated by PropTech.")
	}

	stream := c.String()
	objs := []string{
		"<< /Type /Catalog /Pages 2 0 R >>",
		"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
		"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R " +
			"/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>",
		fmt.Sprintf("<< /Length %d >>\nstream\n%sendstream", len(stream), stream),
		"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
		"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
	}

	var out bytes.Buffer
	out.WriteString("%PDF-1.4\n")
	offsets := make([]int, len(objs))
	for i, o := range objs {
		offsets[i] = out.Len()
		fmt.Fprintf(&out, "%d 0 obj\n%s\nendobj\n", i+1, o)
	}
	xref := out.Len()
	fmt.Fprintf(&out, "xref\n0 %d\n", len(objs)+1)
	out.WriteString("0000000000 65535 f \n")
	for _, off := range offsets {
		fmt.Fprintf(&out, "%010d 00000 n \n", off)
	}
	fmt.Fprintf(&out, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(objs)+1, xref)
	return out.Bytes()
}